SELECT
    COUNT(*) AS total_records,
    COUNT(*) FILTER (WHERE result_status = 'Pass') AS passed,
    COUNT(*) FILTER (WHERE result_status = 'Fail') AS failed,
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE result_status = 'Pass')
        / NULLIF(COUNT(*), 0), 2
    ) AS pass_percentage,
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE result_status = 'Fail')
        / NULLIF(COUNT(*), 0), 2
    ) AS fail_percentage
FROM public.vw_exam_result_details;

SELECT
    department_name,
    ROUND(AVG(
        (marks_obtained * 100.0) / NULLIF(max_marks, 0)
    ), 2) AS average_percentage,
    COUNT(*) AS total_records
FROM public.vw_exam_result_details
GROUP BY department_name
ORDER BY department_name;

SELECT
    'Semester' AS analysis_type,
    semester_number::text AS category,
    ROUND(AVG(marks_obtained * 100.0 /
        NULLIF(max_marks, 0)), 2) AS average_percentage,
    COUNT(*) AS total_records
FROM public.vw_exam_result_details
GROUP BY semester_number

UNION ALL

SELECT
    'Exam Type' AS analysis_type,
    exam_type AS category,
    ROUND(AVG(marks_obtained * 100.0 /
        NULLIF(max_marks, 0)), 2) AS average_percentage,
    COUNT(*) AS total_records
FROM public.vw_exam_result_details
GROUP BY exam_type

ORDER BY analysis_type, category;