INSERT INTO fact_exam_results (
    student_key,
    offering_key,
    exam_type,
    marks_obtained,
    max_marks,
    result_status
)
SELECT
    s.student_key,
    o.offering_key,
    e.exam_type,

    CASE
        WHEN e.exam_type = 'Mid Semester'
        THEN 10 + MOD(s.student_key * 7 + o.offering_key * 11, 41)
        ELSE 25 + MOD(s.student_key * 7 + o.offering_key * 11, 76)
    END AS marks_obtained,

    CASE
        WHEN e.exam_type = 'Mid Semester' THEN 50
        ELSE 100
    END AS max_marks,

    CASE
        WHEN e.exam_type = 'Mid Semester'
             AND (10 + MOD(s.student_key * 7 + o.offering_key * 11, 41)) < 20
        THEN 'Fail'

        WHEN e.exam_type = 'End Semester'
             AND (25 + MOD(s.student_key * 7 + o.offering_key * 11, 76)) < 40
        THEN 'Fail'

        ELSE 'Pass'
    END AS result_status

FROM dim_student s
JOIN fact_course_offering o
    ON o.department_key = s.department_key

CROSS JOIN (
    VALUES
        ('Mid Semester'),
        ('End Semester')
) AS e(exam_type)

WHERE NOT EXISTS (
    SELECT 1
    FROM fact_exam_results existing
    WHERE existing.student_key = s.student_key
      AND existing.offering_key = o.offering_key
      AND existing.exam_type = e.exam_type
);

