
-- 1. Department Dimension
CREATE TABLE dim_department (
    department_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    department_id VARCHAR(10) UNIQUE NOT NULL,
    department_name VARCHAR(100) NOT NULL
);

-- 2. Student Dimension
CREATE TABLE dim_student (
    student_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) UNIQUE NOT NULL,
    student_name VARCHAR(100) NOT NULL,
    gender VARCHAR(10),
    department_key INTEGER REFERENCES dim_department(department_key)
);

-- 3. Course Dimension
CREATE TABLE dim_course (
    course_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    course_id VARCHAR(20) UNIQUE NOT NULL,
    course_name VARCHAR(100) NOT NULL,
    department_key INTEGER REFERENCES dim_department(department_key)
);

-- 4. Semester Dimension
CREATE TABLE dim_semester (
    semester_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    semester_number INTEGER NOT NULL,
    semester_name VARCHAR(30)
);

-- 5. Academic Year Dimension
CREATE TABLE dim_academic_year (
    academic_year_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    academic_year VARCHAR(20) UNIQUE NOT NULL
);

-- 6. Examination Results Fact Table
CREATE TABLE fact_exam_results (
    result_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    student_key INTEGER REFERENCES dim_student(student_key),
    course_key INTEGER REFERENCES dim_course(course_key),
    semester_key INTEGER REFERENCES dim_semester(semester_key),
    academic_year_key INTEGER REFERENCES dim_academic_year(academic_year_key),
    exam_type VARCHAR(30),
    marks_obtained NUMERIC(5,2),
    max_marks NUMERIC(5,2),
    result_status VARCHAR(10),
    CHECK (marks_obtained >= 0),
    CHECK (max_marks > 0),
    CHECK (marks_obtained <= max_marks)
);

