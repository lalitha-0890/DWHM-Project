    COUNT(*) FILTER (
        WHERE er.result_status = 'Pass'
    ) AS passed,

    COUNT(*) FILTER (
        WHERE er.result_status = 'Fail'
    ) AS failed,

    ROUND(
        100.0 * COUNT(*) FILTER (
            WHERE er.result_status = 'Pass'
        ) / NULLIF(COUNT(*), 0),
